import { test, expect } from './fixtures'

test('余额快照与确认收入进入模拟结果，旧余额不冒充真实余额', async ({ page }) => {
  await page.goto('/simulate')
  await page.getByRole('button', { name: /余额与确认收支/ }).click()
  await page.getByLabel('使用余额快照').check()
  await page.getByRole('spinbutton', { name: '快照日结束时的余额' }).fill('10000')
  await page.getByRole('button', { name: '添加确认收支' }).click()
  await page.getByRole('spinbutton', { name: '收支金额 1' }).fill('3000')
  const response = page.waitForResponse(r => r.url().endsWith('/api/simulate') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '运行下月模拟' }).click()
  const result = await (await response).json()
  expect(result.balance_basis).toBe('confirmed_snapshot')
  expect(result.timeline.at(-1).after_cents).toBe(1300000)
  await expect(page.getByRole('heading', { name: /下月预计余额/ })).toBeVisible()
  await expect(page.getByTestId('forecast-evidence')).toContainText('固定账单')
  await page.getByRole('button', { name: '保存方案', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '方案已保存' })).toBeVisible()
  const closeBrief = page.getByRole('button', { name: '关闭简报' })
  if (await closeBrief.isVisible()) await closeBrief.click()
  await page.screenshot({ path: test.info().outputPath('forecast-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: /下月预计余额/ })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('forecast-mobile.png'), fullPage: true })
})

test('完整历史区间自动保存并进入预测结果', async ({ page }) => {
  await page.goto('/settings')
  await page.getByRole('button', { name: '添加完整记录区间' }).click()
  await page.getByLabel('覆盖开始 1').fill('2026-09-01')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/settings') && r.request().method() === 'PUT' &&
    r.request().postDataJSON().history_coverage?.[0]?.end_date === '2026-10-31')
  await page.getByLabel('覆盖结束 1').fill('2026-10-31')
  expect((await saved).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByLabel('覆盖开始 1')).toHaveValue('2026-09-01')
  await expect(page.getByLabel('覆盖结束 1')).toHaveValue('2026-10-31')
  await page.goto('/simulate')
  const response = page.waitForResponse(r => r.url().endsWith('/api/simulate') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '运行下月模拟' }).click()
  expect((await (await response).json()).coverage_status).toBe('confirmed')
  await expect(page.getByTestId('forecast-evidence')).toContainText('已使用你确认的完整记录区间')
})

test('分类削减偏好随模拟请求发送并可恢复默认', async ({ page }) => {
  await page.goto('/simulate')
  await page.getByRole('button', { name: /分类削减偏好/ }).click()
  await page.getByLabel('添加分类约束').selectOption('餐饮')
  await page.getByRole('spinbutton', { name: '餐饮最低保留' }).fill('500')
  await page.getByLabel('餐饮削减上限').fill('20')
  await page.getByLabel('餐饮影响权重').fill('5')
  const request = page.waitForRequest(r => r.url().endsWith('/api/simulate') && r.method() === 'POST')
  await page.getByRole('button', { name: '运行下月模拟' }).click()
  expect((await request).postDataJSON().category_constraints).toEqual([
    { category: '餐饮', minimum_cents: 50000, max_cut_percent: 20, disruption_weight: 5 },
  ])
  await page.getByRole('button', { name: '恢复默认约束' }).click()
  await expect(page.getByLabel('餐饮削减上限')).toHaveCount(0)
})
