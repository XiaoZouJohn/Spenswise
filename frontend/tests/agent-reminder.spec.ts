import { test, expect } from './fixtures'

test.setTimeout(90000)

test('村庄安静更新简报，刷新和新窗口均由用户展开', async ({ page, context }) => {
  await page.goto('/overview')
  const panel = page.getByRole('region', { name: 'Agent 财务简报' })
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '查看财务简报' }).click()
  await expect(panel).toBeVisible()
  await expect(panel).toContainText('本地规则')
  await panel.getByRole('button', { name: '关闭简报' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '查看财务简报' })).toBeVisible()
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '查看财务简报' }).click()
  await expect(panel).toBeVisible()
  const reopened = await context.newPage()
  await reopened.goto('/overview')
  await expect(reopened.getByRole('button', { name: '查看财务简报' })).toBeVisible()
  await expect(reopened.getByRole('region', { name: 'Agent 财务简报' })).toBeHidden()
  await reopened.close()
})

test('记账和跨过预算线均不打断阅读，手动查看最新提醒', async ({ page }) => {
  test.setTimeout(120000)
  await page.goto('/ledger')
  const panel = page.getByRole('region', { name: 'Agent 财务简报' })
  await expect(panel).toBeHidden()
  await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('10')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('共 1 笔', { exact: true })).toBeVisible()
  await expect(panel).toBeHidden()
  await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('3100')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('共 2 笔', { exact: true })).toBeVisible()
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '查看财务简报' }).click()
  await expect(panel).toBeVisible({ timeout: 40000 })
  await expect(panel).toContainText('本月总预算已超额')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await panel.getByRole('button', { name: '关闭简报' }).click()
  await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('1')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('共 3 笔', { exact: true })).toBeVisible()
  await expect(panel).toBeHidden()
})

test('关闭自动提醒可持久保存，仍能手动查看，窄屏可关闭', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/settings')
  const panel = page.getByRole('region', { name: 'Agent 财务简报' })
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '查看财务简报' }).click()
  await expect(panel).toBeVisible()
  const box = await panel.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await panel.getByRole('button', { name: '关闭简报' }).click()
  await page.getByLabel('打开软件和重要变化时自动提醒').click()
  await expect(page.getByLabel('打开软件和重要变化时自动提醒')).not.toBeChecked()
  await expect(page.getByText('提醒设置已保存', { exact: true })).toBeVisible()
  const reopened = await context.newPage()
  await reopened.goto('/overview')
  await expect(reopened.getByRole('button', { name: '查看财务简报' })).toBeVisible()
  await expect(reopened.getByRole('region', { name: 'Agent 财务简报' })).toBeHidden()
  await reopened.getByRole('button', { name: '查看财务简报' }).click()
  await expect(reopened.getByRole('region', { name: 'Agent 财务简报' })).toBeVisible()
  await reopened.close()
})

test('多窗口只修改所选开关，不恢复另一窗口已撤销的 AI 授权', async ({ page, context }) => {
  await context.request.put('http://127.0.0.1:18080/api/agent/preferences', { data: { ai_enabled: true } })
  await page.goto('/settings')
  await expect(page.getByText(/Agent 简报仅发送本人账本汇总和提醒依据/)).toBeVisible()
  await context.request.put('http://127.0.0.1:18080/api/ai/chat/ledger-consent', { data: { enabled: false } })
  const sent = page.waitForRequest(request => request.url().endsWith('/api/agent/preferences') && request.method() === 'PUT')
  await page.getByLabel('打开软件和重要变化时自动提醒').click()
  await expect(page.getByLabel('打开软件和重要变化时自动提醒')).not.toBeChecked()
  expect((await sent).postDataJSON()).toEqual({ automatic_enabled: false })
  await expect(page.getByText('提醒设置已保存', { exact: true })).toBeVisible()
  const stored = await context.request.get('http://127.0.0.1:18080/api/agent/preferences')
  expect((await stored.json()).ai_enabled).toBe(false)
  const consent = await context.request.get('http://127.0.0.1:18080/api/ai/chat/ledger-consent')
  expect((await consent.json()).enabled).toBe(false)
})

test('周期检查和记账防抖不自动弹窗，手动查看仍反映风险', async ({ page }) => {
  await page.clock.install({ time: new Date() })
  await page.goto('/ledger')
  const panel = page.getByRole('region', { name: 'Agent 财务简报' })
  await expect(panel).toBeHidden()
  await page.clock.pauseAt(new Date())
  await page.clock.runFor(29900)
  const recorded = page.waitForResponse(response => response.url().endsWith('/api/transactions') && response.request().method() === 'POST')
  const refreshed = page.waitForResponse(response => response.url().includes('/api/transactions?') && response.request().method() === 'GET')
  await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('3100')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await (await recorded).finished()
  await (await refreshed).finished()
  await page.clock.runFor(20)
  await expect(page.getByText('共 1 笔', { exact: true })).toBeVisible()
  await page.clock.runFor(200)
  await expect(panel).toBeHidden()
  await page.clock.runFor(1500)
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '查看财务简报' }).click()
  await page.clock.runFor(1500)
  await expect(panel).toBeVisible()
  await expect(panel).toContainText('本月总预算已超额')
})
