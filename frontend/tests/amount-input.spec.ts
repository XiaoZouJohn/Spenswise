import { test, expect } from './fixtures'

test('连续逐键输入大额账单，按分准确保存并清空金额框', async ({ page, context }) => {
  await page.goto('/ledger')
  await page.getByRole('button', { name: '关闭简报' }).click()
  const amount = page.getByRole('spinbutton', { name: '金额', exact: true })
  await amount.click()
  await amount.press('ControlOrMeta+A')
  await amount.pressSequentially('1234567890.12')
  await expect(amount).toHaveValue('1234567890.12')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('共 1 笔', { exact: true })).toBeVisible()
  const saved = await context.request.get('http://127.0.0.1:18080/api/transactions?page=1&page_size=25')
  expect((await saved.json()).items[0].amount_cents).toBe(123456789012)
  await expect(amount).toHaveValue('0.00')
})

test('金额可以清空、输入小数、退格修改，失焦后再格式化', async ({ page, context }) => {
  await page.goto('/ledger')
  await page.getByRole('button', { name: '关闭简报' }).click()
  const amount = page.getByRole('spinbutton', { name: '金额', exact: true })
  await amount.click()
  await amount.press('ControlOrMeta+A')
  await amount.press('Backspace')
  await expect(amount).toHaveValue('')
  await expect(page.getByRole('button', { name: '添加', exact: true })).toBeDisabled()
  await amount.pressSequentially('0.05')
  await expect(amount).toHaveValue('0.05')
  await amount.press('Backspace')
  await amount.pressSequentially('6')
  await expect(amount).toHaveValue('0.06')
  await amount.press('ArrowUp')
  await expect(amount).toHaveValue('0.07')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('共 1 笔', { exact: true })).toBeVisible()
  const saved = await context.request.get('http://127.0.0.1:18080/api/transactions?page=1&page_size=25')
  expect((await saved.json()).items[0].amount_cents).toBe(7)
})

test('预算自动保存不打断正在输入的数字，刷新后金额一致', async ({ page, context }) => {
  await page.goto('/settings')
  await page.getByRole('button', { name: '关闭简报' }).click()
  const amount = page.getByRole('spinbutton', { name: '每月总消费上限' })
  await amount.click()
  await amount.press('ControlOrMeta+A')
  await amount.pressSequentially('123')
  await expect(amount).toHaveValue('123')
  await expect.poll(async () => (await (await context.request.get('http://127.0.0.1:18080/api/settings')).json()).monthly_budget_cents).toBe(12300)
  await amount.pressSequentially('456.78')
  await expect(amount).toHaveValue('123456.78')
  await amount.press('Tab')
  await expect.poll(async () => (await (await context.request.get('http://127.0.0.1:18080/api/settings')).json()).monthly_budget_cents).toBe(12345678)
  await page.reload()
  await expect(amount).toHaveValue('123456.78')
})
