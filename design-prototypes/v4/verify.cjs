const { chromium } = require('../../frontend/node_modules/playwright')
const path = require('path')
const { pathToFileURL } = require('url')
;(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
  const page = await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'})
  for (const name of ['astra','port','archive','moss']) {
    const errors=[]
    const errorHandler=e=>errors.push(e.message)
    page.on('pageerror',errorHandler)
    await page.goto(pathToFileURL(path.join(__dirname,`${name}.html`)).href)
    await page.screenshot({path:path.join(__dirname,`${name}-preview.png`),fullPage:true})
    await page.locator('[data-prompt]').first().click()
    if(!await page.locator('textarea').inputValue())throw Error(`${name}: suggestion failed`)
    await page.locator('textarea').press('Enter')
    if(!await page.locator('.response').isVisible())throw Error(`${name}: response missing`)
    await page.locator('header [data-open=plan]').click()
    if(!await page.locator('dialog').isVisible())throw Error(`${name}: dialog failed`)
    await page.keyboard.press('Escape')
    await page.locator('.attachment').click()
    await page.locator('input[type=file]').setInputFiles({name:'演示账单.csv',mimeType:'text/csv',buffer:Buffer.from('date,amount\n')})
    if(!await page.locator('.selected-file').textContent().then(x=>x.includes('演示账单')))throw Error(`${name}: file feedback missing`)
    await page.locator('.close').click()
    await page.setViewportSize({width:390,height:844})
    await page.reload()
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error(`${name}: mobile horizontal overflow`)
    await page.screenshot({path:path.join(__dirname,`${name}-mobile.png`),fullPage:true})
    await page.locator('textarea').fill('查看本月支出变化')
    await page.locator('.send').click()
    if(!await page.locator('.response').isVisible())throw Error(`${name}: mobile response missing`)
    await page.setViewportSize({width:1440,height:960})
    if(errors.length)throw Error(`${name}: ${errors.join('; ')}`)
    page.off('pageerror',errorHandler)
    console.log(`${name}: desktop/mobile, question, dialog, file feedback passed`)
  }
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href)
  await page.screenshot({path:path.join(__dirname,'overview.png'),fullPage:true})
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
